// Package ed25519key checks an Ed25519 public key before a signature is
// verified under it.
//
// crypto/ed25519 verifies under any encoding of a curve point, a point of
// small order among them. Under such a key a signature anyone can make
// verifies, the identity point's for every message, so a key of small
// order proves nothing about who signed. mls and messaging refuse one
// wherever a key comes from someone else.
package ed25519key

// smallOrder are the encodings, with the sign bit of x cleared, of the
