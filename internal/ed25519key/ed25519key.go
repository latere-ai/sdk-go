// SmallOrder reports whether pub, an Ed25519 public key of 32 bytes,
// encodes a point of small order. A key of another length is not one;
// its length is the caller's to check.
func SmallOrder(pub []byte) bool {
	if len(pub) != 32 {
		return false
	}
	for _, s := range smallOrder {
		var diff byte
		for i := range 31 {
			diff |= pub[i] ^ s[i]
		}
		diff |= (pub[31] & 0x7f) ^ s[31]
		if diff == 0 {
			return true
		}
	}
	return false
}
